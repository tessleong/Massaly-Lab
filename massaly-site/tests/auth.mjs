import assert from 'node:assert/strict';
import worker from '../dist/server/index.js';
const env={TEAM_PASSWORD:'test-password',TEAM_SESSION_SECRET:'test-only-secret-value'};
const origin='https://site.test';
const request=(path,init={})=>worker.fetch(new Request(origin+path,init),env);
assert.equal((await request('/member-resources')).status,401);
assert.equal((await request('/member-resources.html')).status,401);
assert.equal((await request('/private/member-resources.html')).status,404);
assert.equal((await request('/server/index.js')).status,404);
const login=p=>request('/team-login',{method:'POST',headers:{Origin:origin,Accept:'application/json'},body:new URLSearchParams({password:p})});
assert.equal((await login('wrong')).status,401);
assert.equal((await request('/team-login',{method:'POST',headers:{Origin:'https://evil.test'},body:'password=test-password'})).status,403);
const success=await login(env.TEAM_PASSWORD);assert.equal(success.status,200);
const header=success.headers.get('set-cookie');assert(header.includes('HttpOnly; Secure; SameSite=Strict'));
const cookie=header.split(';')[0];
const page=await request('/member-resources',{headers:{Cookie:cookie}});assert.equal(page.status,200);assert((await page.text()).includes('Undergraduate Research Assistant onboarding'));assert.equal(page.headers.get('cache-control'),'no-store');
assert.equal((await request('/member-resources',{headers:{Cookie:cookie.slice(0,-1)+'z'}})).status,401);
assert.equal((await worker.fetch(new Request(origin+'/member-resources',{headers:{Cookie:cookie}}),{...env,TEAM_PASSWORD:'changed'})).status,401);
const logout=await request('/team-logout',{method:'POST',headers:{Origin:origin,Cookie:cookie}});assert.equal(logout.status,303);assert(logout.headers.get('set-cookie').includes('Max-Age=0'));
for(let i=0;i<10;i++)assert.equal((await login('wrong')).status,401);
assert.equal((await login('wrong')).status,429);
for(const path of ['/','/our-team','/our-values','/contact','/style.css','/logo.webp'])assert.equal((await request(path)).status,200);
console.log('Passed protected routes, credential checking, signed sessions, tamper rejection, password rotation, logout, request-origin checks, throttling and public pages.');
